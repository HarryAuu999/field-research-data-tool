import assert from "node:assert/strict";
import fs from "node:fs/promises";
import { chromium } from "playwright";
import JSZip from "jszip";

const base = process.env.AUNOTE_TEST_URL || "http://127.0.0.1:4196/";
const browser = await chromium.launch({ headless: true, executablePath: process.env.AUNOTE_CHROME_PATH || "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe" });
const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, acceptDownloads: true });
const page = await context.newPage();
const errors = [];
page.on("pageerror", (error) => errors.push(error.message));

async function setAngle(value) {
  await page.locator("[data-angle-slider]").evaluate((input, angle) => {
    input.value = String(angle);
    input.dispatchEvent(new Event("input", { bubbles: true }));
  }, value);
  assert.equal(await page.locator("[data-angle-value]").textContent(), `${value}°`);
}

try {
  await fs.mkdir("test-results", { recursive: true });
  await page.goto(base, { waitUntil: "networkidle" });
  await page.locator(".hero-title").waitFor();
  assert.equal(await page.evaluate(async () => {
    const { getTemplates } = await import("./js/db.js");
    return (await getTemplates()).some((template) => template.id === "ear-clip-angle-preview");
  }), false, "正式初始化不得自动安装角度测试问卷");
  await page.goto(new URL("preview/image-angle.html", base).href, { waitUntil: "networkidle" });
  await page.locator(".hero-title", { hasText: "耳夹C桥角度测试" }).waitFor();
  await page.locator('[data-action="start-form"]').click();
  assert.equal(await page.locator("[data-angle-value]").textContent(), "未选择");
  assert.equal(await page.locator(".form-counter").textContent(), "1/1");
  assert.equal(await page.locator(".question-image").count(), 0, "底图不能重复显示");
  const box = await page.locator("[data-angle-slider]").boundingBox();
  const startX = box.x + 17.6 + (box.width - 35.2) * 20 / 110;
  const y = box.y + box.height / 2;
  const cdp = await context.newCDPSession(page);
  await cdp.send("Input.dispatchTouchEvent", { type: "touchStart", touchPoints: [{ x: startX, y, id: 1 }] });
  await cdp.send("Input.dispatchTouchEvent", { type: "touchEnd", touchPoints: [] });
  await page.locator('[data-angle-value]', { hasText: "0°" }).waitFor();
  await page.locator("[data-angle-clear]").click();
  assert.equal(await page.locator("[data-angle-value]").textContent(), "未选择");
  await cdp.send("Input.dispatchTouchEvent", { type: "touchStart", touchPoints: [{ x: startX, y, id: 1 }] });
  for (let i = 1; i <= 5; i++) await cdp.send("Input.dispatchTouchEvent", { type: "touchMove", touchPoints: [{ x: startX + (box.width - 35.2) * (45 / 110) * i / 5, y, id: 1 }] });
  await cdp.send("Input.dispatchTouchEvent", { type: "touchEnd", touchPoints: [] });
  assert.ok(Math.abs(Number(await page.locator("[data-angle-slider]").inputValue()) - 45) <= 1, "真实触控应调整角度");
  assert.equal(await page.evaluate(() => window.scrollY), 0, "调节时页面不能上下滚动");
  const nav = await page.locator(".form-navigation").boundingBox();
  assert.ok(nav.y + nav.height <= 845, "手机上底部按钮须在屏内");
  await setAngle(-20);
  const up = await page.locator("[data-angle-ray]").evaluate((line) => ({ x1: +line.getAttribute("x1"), y1: +line.getAttribute("y1"), x2: +line.getAttribute("x2"), y2: +line.getAttribute("y2") }));
  assert.ok(up.x2 < up.x1 && up.y2 < up.y1);
  await setAngle(90);
  const down = await page.locator("[data-angle-ray]").evaluate((line) => ({ x1: +line.getAttribute("x1"), y1: +line.getAttribute("y1"), x2: +line.getAttribute("x2"), y2: +line.getAttribute("y2") }));
  assert.ok(Math.abs(down.x2 - down.x1) < 0.001 && down.y2 > down.y1);
  await setAngle(0);
  await page.screenshot({ path: "test-results/image-angle-form.png", fullPage: true });
  await page.locator('[data-action="leave-form"]').click();
  await page.reload({ waitUntil: "networkidle" });
  await page.locator('[data-action="continue-draft"]').click();
  assert.equal(await page.locator("[data-angle-value]").textContent(), "0°", "刷新后恢复草稿角度");
  await page.locator('[data-action="next-question"]').click();
  for (const value of [-20, 90, 30, 30, 40]) {
    await page.locator('[data-action="start-form"]').click();
    assert.equal(await page.locator("[data-angle-value]").textContent(), "未选择", "新样本不能沿用上一人的角度");
    await setAngle(value);
    await page.locator('[data-action="next-question"]').click();
  }
  await page.locator('[data-action="analysis"]').click();
  await page.locator(".image-angle-chart").waitFor();
  const total = await page.locator("[data-angle-bin]").evaluateAll((bars) => bars.reduce((sum, bar) => sum + Number(bar.dataset.count), 0));
  assert.equal(total, 6);
  const bars = await page.locator("[data-angle-bin]").evaluateAll((paths) => paths.map((path) => {
    const style = getComputedStyle(path);
    return { count: Number(path.dataset.count), radii: [...path.getAttribute("d").matchAll(/A\s+([\d.]+)/g)].map((match) => Number(match[1])), opacity: style.fillOpacity, stroke: style.stroke, width: style.strokeWidth };
  }));
  assert.ok(bars.every((bar) => bar.radii.length === 2 && bar.radii[1] > 0), "柱形应从中心留空的基准弧开始");
  const unitLength = (bars[0].radii[0] - bars[0].radii[1]) / bars[0].count;
  assert.ok(bars.every((bar) => Math.abs((bar.radii[0] - bar.radii[1]) / bar.count - unitLength) < 0.001), "基准弧外的柱长必须与人数成比例");
  assert.ok(bars.every((bar) => bar.opacity === "0.8" && bar.stroke === "none" && bar.width === "0px"));
  assert.match(await page.locator(".image-angle-statistics").textContent(), /中位数\s*30°/);
  assert.match(await page.locator(".image-angle-statistics").textContent(), /平均数\s*28\.33°/);
  assert.match(await page.locator(".image-angle-statistics").textContent(), /标准差\s*37\.64°/);
  assert.equal(await page.locator(".image-angle-chart .angle-chart-mean").evaluate((line) => getComputedStyle(line).strokeDasharray), "none");
  assert.match(await page.locator(".image-angle-legend").textContent(), /平均数/);
  assert.doesNotMatch(await page.locator(".image-angle-legend").textContent(), /基准弧外柱长/);
  assert.equal(await page.locator("[data-angle-bin-info]").isVisible(), false);
  const cardHeight = (await page.locator(".image-angle-analysis").boundingBox()).height;
  await page.locator('[data-angle-bin][data-count="2"]').focus();
  await page.keyboard.press("Enter");
  assert.match(await page.locator("[data-angle-bin-info]").textContent(), /2人/);
  assert.equal(await page.locator('[data-angle-bin][aria-pressed="true"]').count(), 1);
  const selectedStyle = await page.locator('[data-angle-bin][aria-pressed="true"]').evaluate((bar) => {
    const style = getComputedStyle(bar);
    return { outline: style.outlineStyle, stroke: style.stroke, width: style.strokeWidth };
  });
  assert.equal(selectedStyle.outline, "none");
  assert.equal(selectedStyle.stroke, "rgb(0, 0, 0)");
  assert.equal(selectedStyle.width, "1.5px");
  assert.equal(await page.locator("[data-angle-bin-info]").evaluate((info) => getComputedStyle(info).color), "rgb(0, 0, 0)");
  assert.equal(await page.locator("[data-angle-bin-info]").evaluate((info) => getComputedStyle(info).fontWeight), "700");
  assert.equal((await page.locator(".image-angle-analysis").boundingBox()).height, cardHeight, "选中人数说明不能改变页面高度");
  assert.equal(await page.locator(".image-angle-chart [data-angle-bin-info]").count(), 1);
  await page.screenshot({ path: "test-results/image-angle-selected.png", fullPage: true });
  await page.locator(".image-angle-analysis summary").click();
  assert.equal(await page.locator(".image-angle-analysis details").getAttribute("open"), "", "选中扇形后一次点击就应展开统计");
  assert.deepEqual(await page.locator(".image-angle-ranges dt").allTextContents(), ["Min", "Max", "P5", "P10", "P25", "P75", "P90", "P95"]);
  assert.deepEqual(await page.locator(".image-angle-ranges dd").allTextContents(), ["-20°", "90°", "-15°", "-10°", "7.5°", "37.5°", "65°", "77.5°"]);
  await page.screenshot({ path: "test-results/image-angle-detailed-statistics.png", fullPage: true });
  await page.locator(".image-angle-analysis summary").click();
  await page.locator(".image-angle-analysis h2").click();
  assert.equal(await page.locator('[data-angle-bin][aria-pressed="true"]').count(), 0);
  assert.equal(await page.locator("[data-angle-bin-info]").isVisible(), false);
  assert.equal(await page.locator("[data-angle-bin-info]").textContent(), "");
  assert.equal(await page.locator(".image-angle-analysis summary").textContent(), "详细统计数据");
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: "test-results/image-angle-analysis.png", fullPage: true });
  await page.locator('[data-action="home"]').click();
  await page.locator('[data-action="records"]').click();
  await page.locator('[data-action="open-record"]').filter({ has: page.locator('.record-name', { hasText: /^0°$/ }) }).click();
  await page.locator('[data-action="edit-record-at"]').click();
  assert.equal(await page.locator("[data-angle-value]").textContent(), "0°", "历史样本的水平角度应恢复");
  await setAngle(10);
  await page.locator('[data-action="next-question"]').click();
  assert.match(await page.locator(".detail-value").textContent(), /10°/);
  await page.locator('[data-action="records"]').click();
  await page.locator('[data-action="home"]').click();
  const downloadPromise = page.waitForEvent("download");
  await page.locator('[data-action="export-xlsx"]').click();
  const download = await downloadPromise;
  await download.saveAs("test-results/image-angle-export.xlsx");
  const zip = await JSZip.loadAsync(await fs.readFile("test-results/image-angle-export.xlsx"));
  const sheet = await zip.file("xl/worksheets/sheet1.xml").async("string");
  assert.match(sheet, /耳夹C桥佩戴角度（°）/);
  assert.match(sheet, /<v>-20<\/v>/, "负角度应以数值导出");
  assert.match(sheet, /<v>90<\/v>/);
  assert.match(sheet, /<v>10<\/v>/, "修改写回原样本");
  const metadata = await zip.file("xl/worksheets/sheet3.xml").async("string");
  assert.match(metadata, /responseColumn/);
  assert.match(metadata, /wearAngle/);
  assert.match(metadata, /counterclockwise/);
  assert.match(metadata, /ear-side.png/);
  await page.reload({ waitUntil: "networkidle" });
  await page.evaluate(() => navigator.serviceWorker.ready);
  await context.setOffline(true);
  await page.reload({ waitUntil: "networkidle" });
  await page.locator('[data-action="start-form"]').click();
  await setAngle(22);
  await context.setOffline(false);
  const desktop = await browser.newContext({ viewport: { width: 1024, height: 900 } });
  const desktopPage = await desktop.newPage();
  await desktopPage.goto(new URL("preview/image-angle.html", base).href, { waitUntil: "networkidle" });
  await desktopPage.locator('[data-action="start-form"]').click();
  const desktopSlider = await desktopPage.locator("[data-angle-slider]").boundingBox();
  await desktopPage.mouse.click(desktopSlider.x + desktopSlider.width - 16, desktopSlider.y + desktopSlider.height / 2);
  assert.equal(await desktopPage.locator("[data-angle-value]").textContent(), "90°", "鼠标点击可选择上限");
  assert.equal(await desktopPage.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await desktop.close();
  assert.equal(errors.length, 0, errors.join("\n"));
  console.log(JSON.stringify({ passed: true, scenarios: ["touch-slider", "mouse-slider", "empty-vs-zero", "direction", "one-screen", "draft-reload", "multiple-samples", "polar-counts", "record-edit", "numeric-xlsx-and-metadata", "offline"] }, null, 2));
} finally {
  await context.close();
  await browser.close();
}
